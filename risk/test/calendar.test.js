"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { nyseHolidays, isOpen, expectedLatest, missingOpenDays } = require("../lib/calendar");
const H = require("./helpers");

// NYSE Group「2026, 2027 and 2028 Holiday and Early Closings Calendar」（2025-12-23 発表）の休場日
const OFFICIAL = {
  2026: ["2026-01-01", "2026-01-19", "2026-02-16", "2026-04-03", "2026-05-25", "2026-06-19", "2026-07-03", "2026-09-07", "2026-11-26", "2026-12-25"],
  2027: ["2027-01-01", "2027-01-18", "2027-02-15", "2027-03-26", "2027-05-31", "2027-06-18", "2027-07-05", "2027-09-06", "2027-11-25", "2027-12-24"],
  // 2028年は元日が土曜で休場なし
  2028: ["2028-01-17", "2028-02-21", "2028-04-14", "2028-05-29", "2028-06-19", "2028-07-04", "2028-09-04", "2028-11-23", "2028-12-25"],
};

test("NYSE の休場日が、2026〜2028年の公式発表と一致する", () => {
  for (const [y, days] of Object.entries(OFFICIAL)) assert.deepEqual([...nyseHolidays(Number(y))].sort(), days, y);
});

test("元日が土曜の年（2028年）は、前の年の12/31（金）は開いている", () => {
  assert.equal(isOpen("2027-12-31"), true);
});

test("コロンブス・デー、退役軍人の日は開いている（債券市場とは違う）。土日は休み", () => {
  assert.equal(isOpen("2026-10-12"), true);
  assert.equal(isOpen("2026-11-11"), true);
  assert.equal(isOpen("2026-10-31"), false);
  assert.equal(isOpen("2026-11-01"), false);
});

test("規則で決まらない休場（追悼の日など）は extraClosed で足せる", () => {
  assert.equal(isOpen("2026-10-29", ["2026-10-29"]), false);
});

test("期待する最新日：米東部18:00を境に、その日の値があるはずとみなす。夏時間の終わり（11/1）と休場を飛ばす", () => {
  const opts = { readyMin: 18 * 60 };
  const cases = [
    ["2026-10-30 10:00", "2026-10-29"], // 米東部 10/29 21:00（夏時間）
    ["2026-10-30 06:59", "2026-10-28"], // 米東部 10/29 17:59
    ["2026-10-30 07:00", "2026-10-29"], // 米東部 10/29 18:00（境界を含む）
    ["2026-10-31 10:00", "2026-10-30"], // 土曜の朝＝金曜の値
    ["2026-11-02 10:00", "2026-10-30"], // 月曜の朝（米東部は日曜 20:00。冬時間）
    ["2026-11-03 07:59", "2026-10-30"], // 米東部 11/2 17:59（冬時間）
    ["2026-11-03 08:00", "2026-11-02"], // 米東部 11/2 18:00
    ["2026-11-27 10:00", "2026-11-25"], // 感謝祭（11/26）の翌朝
    ["2026-04-04 10:00", "2026-04-02"], // 聖金曜（4/3）の翌朝
    ["2026-07-04 10:00", "2026-07-02"], // 独立記念日の振替（7/3 金）の翌朝
    ["2027-01-02 10:00", "2026-12-31"], // 元日（2027-01-01 金）の翌朝
  ];
  for (const [now, want] of cases) assert.equal(expectedLatest(H.jst(now), opts), want, now);
});

test("行が無い営業日（穴）を見つける。休場日・土日は穴に数えない", () => {
  assert.deepEqual(missingOpenDays(["2026-11-24", "2026-11-25", "2026-11-27", "2026-11-30"]), []);
  assert.deepEqual(missingOpenDays(["2026-11-24", "2026-11-27"]), ["2026-11-25"]);
});
